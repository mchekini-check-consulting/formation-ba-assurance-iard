-- T-05 : le devis enregistré (devis_enregistre = « devis » du dictionnaire) devient multi-produit.
-- Colonnes existantes réutilisées (aucun renommage) : formule = formule choisie, prix_mensuel = prime mensuelle TTC,
-- date_fin_validite = date de validité. La colonne statut existante (situation de l'occupant du logement) n'est pas
-- touchée : le statut du devis va dans statut_devis.

ALTER TABLE devis_enregistre
    ADD COLUMN produit                 VARCHAR(12) NOT NULL DEFAULT 'HABITATION',
    ADD COLUMN statut_devis            VARCHAR(20) NOT NULL DEFAULT 'EN_COURS',
    ADD COLUMN formule_conseillee      VARCHAR(20),
    ADD COLUMN choix_different_conseil BOOLEAN,
    ADD COLUMN reponses_besoins        JSONB,
    ADD COLUMN date_modification       TIMESTAMP WITH TIME ZONE;

-- Reprise des devis du sprint 1 : formule conseillée = celle de la recommandation ; statut du devis :
-- TRANSFORME si un contrat existe pour ce devis, EXPIRE si la validité est dépassée, sinon EN_COURS.
UPDATE devis_enregistre d
SET formule_conseillee      = r.formule,
    choix_different_conseil = (LOWER(d.formule) <> LOWER(r.formule))
FROM recommandation_devis r
WHERE r.reference = d.reference;

UPDATE devis_enregistre d
SET statut_devis = CASE
        WHEN EXISTS (SELECT 1
                     FROM contrat c
                     JOIN dossier_souscription ds ON ds.id = c.dossier_id
                     WHERE ds.compte_id = d.compte_id AND ds.reference_devis = d.reference) THEN 'TRANSFORME'
        WHEN d.date_fin_validite < CURRENT_DATE THEN 'EXPIRE'
        ELSE 'EN_COURS'
    END;

-- Un devis auto n'a ni logement ni recommandation habitation ; à ses premières étapes il n'a pas encore de
-- formule ni de prix. Ces colonnes restent obligatoires pour un devis habitation.
ALTER TABLE devis_enregistre
    ALTER COLUMN reference DROP NOT NULL,
    ALTER COLUMN type_logement DROP NOT NULL,
    ALTER COLUMN adresse DROP NOT NULL,
    ALTER COLUMN code_postal DROP NOT NULL,
    ALTER COLUMN ville DROP NOT NULL,
    ALTER COLUMN surface DROP NOT NULL,
    ALTER COLUMN formule DROP NOT NULL,
    ALTER COLUMN options DROP NOT NULL,
    ALTER COLUMN franchise DROP NOT NULL,
    ALTER COLUMN prix_mensuel DROP NOT NULL,
    ADD CONSTRAINT ck_devis_enregistre_produit CHECK (produit IN ('HABITATION', 'AUTO')),
    ADD CONSTRAINT ck_devis_enregistre_statut_devis CHECK (statut_devis IN
        ('EN_COURS', 'VEHICULE_RENSEIGNE', 'BESOINS_RENSEIGNES', 'FORMULE_CHOISIE', 'RECAP_VALIDE', 'TRANSFORME',
         'REFUSE_EN_LIGNE', 'EXPIRE')),
    ADD CONSTRAINT ck_devis_enregistre_habitation CHECK (produit <> 'HABITATION' OR (
        reference IS NOT NULL AND type_logement IS NOT NULL AND adresse IS NOT NULL AND code_postal IS NOT NULL
        AND ville IS NOT NULL AND surface IS NOT NULL AND formule IS NOT NULL AND options IS NOT NULL
        AND franchise IS NOT NULL AND prix_mensuel IS NOT NULL));

-- Volet auto d'un devis (un pour un avec devis_enregistre).
CREATE TABLE devis_auto (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devis_id              BIGINT                   NOT NULL,
    vehicule_id           BIGINT,
    conducteur_id         BIGINT,
    assure_plus_un_an     BOOLEAN                  NOT NULL DEFAULT FALSE,
    ancien_assureur       VARCHAR(100),
    ancien_numero_contrat VARCHAR(40),
    date_effet_souhaitee  DATE,
    date_creation         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_devis_auto_devis UNIQUE (devis_id),
    CONSTRAINT fk_devis_auto_devis FOREIGN KEY (devis_id) REFERENCES devis_enregistre (id),
    CONSTRAINT fk_devis_auto_vehicule FOREIGN KEY (vehicule_id) REFERENCES vehicule (id),
    CONSTRAINT fk_devis_auto_conducteur FOREIGN KEY (conducteur_id) REFERENCES conducteur (id),
    CONSTRAINT ck_devis_auto_ancien_assureur CHECK (NOT assure_plus_un_an
        OR (ancien_assureur IS NOT NULL AND ancien_numero_contrat IS NOT NULL)),
    -- Entre le lendemain et 90 jours, par rapport à la création (la date du jour est contrôlée par l'application).
    CONSTRAINT ck_devis_auto_date_effet CHECK (date_effet_souhaitee IS NULL
        OR date_effet_souhaitee BETWEEN CAST(date_creation AS DATE) + 1 AND CAST(date_creation AS DATE) + 90)
);

CREATE TABLE devis_option (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devis_id          BIGINT                   NOT NULL,
    code_option       VARCHAR(30)              NOT NULL,
    prix_mensuel_ttc  NUMERIC(10, 2)           NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_devis_option UNIQUE (devis_id, code_option),
    CONSTRAINT fk_devis_option_devis FOREIGN KEY (devis_id) REFERENCES devis_enregistre (id)
);
