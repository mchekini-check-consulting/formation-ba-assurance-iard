-- T-05 : référentiels véhicule (structure seule ; les données sont chargées par T-04).
-- Énumérations stockées en texte, limitées par une contrainte (convention T-05).

CREATE TABLE ref_vehicule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marque            VARCHAR(60)              NOT NULL,
    modele            VARCHAR(60)              NOT NULL,
    energie           VARCHAR(12)              NOT NULL,
    version           VARCHAR(60),
    annee             INTEGER,
    valeur_neuve      NUMERIC(10, 2),
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_ref_vehicule_energie CHECK (energie IN ('ESSENCE', 'DIESEL', 'HYBRIDE', 'ELECTRIQUE', 'GPL'))
);

CREATE TABLE ref_plaque_test (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    immatriculation   VARCHAR(10)              NOT NULL,
    ref_vehicule_id   BIGINT,
    comportement      VARCHAR(10)              NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_ref_plaque_test_immatriculation UNIQUE (immatriculation),
    CONSTRAINT fk_ref_plaque_test_vehicule FOREIGN KEY (ref_vehicule_id) REFERENCES ref_vehicule (id),
    CONSTRAINT ck_ref_plaque_test_comportement CHECK (comportement IN ('TROUVE', 'INCONNU', 'ERREUR', 'DELAI'))
);
