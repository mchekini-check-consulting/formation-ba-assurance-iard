-- T-05 : preuve de signature électronique, déclaration au fichier des véhicules assurés (FVA) et résiliation
-- de l'ancien contrat par la loi Hamon. Le code de signature à 6 chiffres reste dans code_signature_contrat (V10).

CREATE TABLE preuve_signature (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrat_id         BIGINT                   NOT NULL,
    document_id        BIGINT,
    empreinte_document VARCHAR(64)              NOT NULL,
    email              VARCHAR(254)             NOT NULL,
    adresse_ip         VARCHAR(45),
    signe_le           TIMESTAMP WITH TIME ZONE NOT NULL,
    nb_essais          INTEGER                  NOT NULL,
    date_creation      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_preuve_signature_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT fk_preuve_signature_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT ck_preuve_signature_nb_essais CHECK (nb_essais BETWEEN 1 AND 3)
);

CREATE INDEX idx_preuve_signature_contrat ON preuve_signature (contrat_id);

CREATE TABLE declaration_fva (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrat_id        BIGINT                   NOT NULL,
    immatriculation   VARCHAR(10),
    statut            VARCHAR(10)              NOT NULL DEFAULT 'A_ENVOYER',
    envoye_le         TIMESTAMP WITH TIME ZONE,
    reference_accuse  VARCHAR(100),
    motif_rejet       VARCHAR(255),
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_declaration_fva_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT ck_declaration_fva_statut CHECK (statut IN ('A_ENVOYER', 'DECLAREE', 'REJETEE', 'DIFFEREE'))
);

CREATE INDEX idx_declaration_fva_contrat ON declaration_fva (contrat_id);

CREATE TABLE resiliation_hamon (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrat_id        BIGINT                   NOT NULL,
    ancien_assureur   VARCHAR(100)             NOT NULL,
    ancien_numero     VARCHAR(40)              NOT NULL,
    statut            VARCHAR(12)              NOT NULL DEFAULT 'A_ENVOYER',
    envoye_le         TIMESTAMP WITH TIME ZONE,
    date_fin_ancien   DATE,
    nb_essais         INTEGER                  NOT NULL DEFAULT 0,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_resiliation_hamon_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT ck_resiliation_hamon_statut CHECK (statut IN
        ('A_ENVOYER', 'ENVOYEE', 'ACCEPTEE', 'INTROUVABLE', 'ERREUR')),
    CONSTRAINT ck_resiliation_hamon_nb_essais CHECK (nb_essais >= 0)
);

CREATE INDEX idx_resiliation_hamon_contrat ON resiliation_hamon (contrat_id);
