-- T-05 : véhicule et conducteur d'un devis ou d'un contrat auto.
-- Règles en base : immatriculation au format AA-123-AA si renseignée ; date d'acquisition entre la mise en
-- circulation et la création de la ligne (la comparaison avec la date du jour est faite par l'application) ;
-- coefficient bonus-malus entre 0,50 et 3,50. Aucune donnée de santé n'est stockée.

CREATE TABLE vehicule (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    immatriculation        VARCHAR(10),
    non_immatricule        BOOLEAN                  NOT NULL DEFAULT FALSE,
    marque                 VARCHAR(60)              NOT NULL,
    modele                 VARCHAR(60)              NOT NULL,
    version                VARCHAR(60),
    energie                VARCHAR(12)              NOT NULL,
    date_mise_circulation  DATE,
    date_acquisition       DATE,
    mode_achat             VARCHAR(10),
    titulaire_carte_grise  VARCHAR(20),
    usage                  VARCHAR(15),
    km_annuel              INTEGER,
    stationnement          VARCHAR(15),
    valeur_estimee         NUMERIC(10, 2),
    source                 VARCHAR(10)              NOT NULL,
    date_creation          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_vehicule_immatriculation CHECK (immatriculation IS NULL OR immatriculation ~ '^[A-Z]{2}-[0-9]{3}-[A-Z]{2}$'),
    CONSTRAINT ck_vehicule_energie CHECK (energie IN ('ESSENCE', 'DIESEL', 'HYBRIDE', 'ELECTRIQUE', 'GPL')),
    CONSTRAINT ck_vehicule_mode_achat CHECK (mode_achat IN ('COMPTANT', 'CREDIT', 'LOA', 'LLD')),
    CONSTRAINT ck_vehicule_titulaire CHECK (titulaire_carte_grise IN
        ('SOUSCRIPTEUR', 'CONJOINT', 'ENFANT', 'SOCIETE_LOCATION', 'AUTRE_PERSONNE')),
    CONSTRAINT ck_vehicule_usage CHECK (usage IN ('PRIVE', 'TRAJET_TRAVAIL', 'PROFESSIONNEL')),
    CONSTRAINT ck_vehicule_stationnement CHECK (stationnement IN ('GARAGE_FERME', 'PARKING_PRIVE', 'RUE')),
    CONSTRAINT ck_vehicule_source CHECK (source IN ('PLAQUE', 'MARQUE')),
    CONSTRAINT ck_vehicule_km_annuel CHECK (km_annuel IS NULL OR km_annuel >= 0),
    CONSTRAINT ck_vehicule_date_acquisition CHECK (
        date_acquisition IS NULL
        OR ((date_mise_circulation IS NULL OR date_acquisition >= date_mise_circulation)
            AND date_acquisition <= CAST(date_creation AS DATE)))
);

CREATE TABLE conducteur (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    est_souscripteur                BOOLEAN                  NOT NULL DEFAULT TRUE,
    date_naissance                  DATE,
    date_permis                     DATE,
    coefficient_bonus_malus         NUMERIC(3, 2),
    annees_assurance                INTEGER,
    nb_sinistres_3_ans              INTEGER,
    resiliation_assureur            VARCHAR(20)              NOT NULL DEFAULT 'AUCUNE',
    suspension_permis               BOOLEAN                  NOT NULL DEFAULT FALSE,
    condamnation_alcool_stupefiants BOOLEAN                  NOT NULL DEFAULT FALSE,
    eligible_en_ligne               BOOLEAN,
    date_creation                   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_conducteur_bonus_malus CHECK (coefficient_bonus_malus BETWEEN 0.50 AND 3.50),
    CONSTRAINT ck_conducteur_resiliation CHECK (resiliation_assureur IN
        ('AUCUNE', 'NON_PAIEMENT', 'SINISTRALITE', 'FAUSSE_DECLARATION')),
    CONSTRAINT ck_conducteur_annees_assurance CHECK (annees_assurance IS NULL OR annees_assurance >= 0),
    CONSTRAINT ck_conducteur_nb_sinistres CHECK (nb_sinistres_3_ans IS NULL OR nb_sinistres_3_ans >= 0)
);
