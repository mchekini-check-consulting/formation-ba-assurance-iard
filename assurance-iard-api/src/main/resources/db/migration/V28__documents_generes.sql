-- T-03 : documents PDF générés (conditions particulières, conditions générales...) et stockés en base.
-- Ajouts seulement : aucune donnée existante n'est modifiée ni supprimée.

-- 1. Référence d'un document : n° de facture, n° d'avenant, produit (HABITATION, AUTO) pour les conditions
--    générales, formule pour un IPID. Vide pour les documents uniques d'un contrat (conditions particulières...).
--    Le contrat reste facultatif (colonne déjà nullable) : les conditions générales ne dépendent d'aucun contrat.
ALTER TABLE document ADD COLUMN reference VARCHAR(40);

-- 2. Une seule version EN_VIGUEUR par contrat, type ET référence (plusieurs factures et avenants par contrat).
--    Les documents sans contrat ne sont concernés que s'ils ont une référence (conditions générales, IPID) ;
--    ceux d'un sinistre ou d'un devis sans contrat restent libres, comme avant.
DROP INDEX uk_document_en_vigueur;
CREATE UNIQUE INDEX uk_document_en_vigueur
    ON document (COALESCE(contrat_id, 0), type, COALESCE(reference, ''))
    WHERE statut = 'EN_VIGUEUR' AND (contrat_id IS NOT NULL OR reference IS NOT NULL);

-- 3. Contenu des PDF, conservé en base (le dossier de fichiers en ligne est vidé à chaque redémarrage).
--    Un contenu par document ; document.cle_stockage = 'base:document_contenu/<document_id>'.
--    Taille limitée à 5 Mo par PDF.
CREATE TABLE document_contenu (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT                   NOT NULL,
    contenu           BYTEA                    NOT NULL,
    taille_octets     INTEGER                  NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_document_contenu_document UNIQUE (document_id),
    CONSTRAINT fk_document_contenu_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT ck_document_contenu_taille CHECK (taille_octets BETWEEN 1 AND 5242880),
    CONSTRAINT ck_document_contenu_taille_reelle CHECK (taille_octets = OCTET_LENGTH(contenu))
);

-- Recherche des documents à stocker par la tâche de reprise.
CREATE INDEX idx_document_a_stocker ON document (id) WHERE NOT stocke;
