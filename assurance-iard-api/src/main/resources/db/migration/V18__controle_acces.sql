-- US-04 : contrôle des accès selon le profil.

-- 1. Le Prospect doit pouvoir souscrire (tunnel de devis, pièces, mandat, contrat) : sans ces droits,
--    le refus par défaut (RG2) bloquerait toute souscription. Le changement est tracé dans l'historique de l'US-02.
INSERT INTO historique_permission
    (modifie_le, modifie_par_email, profil, rubrique, droit, ancienne_valeur, nouvelle_valeur)
SELECT NOW(), 'US-04 (mise à jour automatique)', profil, rubrique, droit, false, true
FROM permission
WHERE profil = 'PROSPECT'
  AND valeur = false
  AND (rubrique, droit) IN (('SOUSCRIPTION', 'CONSULTER'), ('SOUSCRIPTION', 'CREER'), ('SOUSCRIPTION', 'MODIFIER'),
                            ('CONTRATS', 'CONSULTER'), ('DOCUMENTS', 'CONSULTER'), ('DOCUMENTS', 'CREER'));

UPDATE permission
SET valeur = true
WHERE profil = 'PROSPECT'
  AND (rubrique, droit) IN (('SOUSCRIPTION', 'CONSULTER'), ('SOUSCRIPTION', 'CREER'), ('SOUSCRIPTION', 'MODIFIER'),
                            ('CONTRATS', 'CONSULTER'), ('DOCUMENTS', 'CONSULTER'), ('DOCUMENTS', 'CREER'));

-- 2. RG3 : journal des tentatives d'accès refusées, consultable par l'administrateur.
--    Le compte est gardé en copie (e-mail, profil) : la ligne reste lisible si le compte disparaît.
CREATE TABLE acces_refuse (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_tentative TIMESTAMP WITH TIME ZONE NOT NULL,
    compte_id     BIGINT,
    email         VARCHAR(254) NOT NULL,
    profil        VARCHAR(30)  NOT NULL,
    methode       VARCHAR(10)  NOT NULL,
    chemin        VARCHAR(255) NOT NULL,
    ressource     VARCHAR(30)  NOT NULL,
    identifiant   VARCHAR(100),
    rubrique      VARCHAR(30)  NOT NULL,
    droit         VARCHAR(30)  NOT NULL,
    motif         VARCHAR(30)  NOT NULL,
    CONSTRAINT fk_acces_refuse_compte FOREIGN KEY (compte_id) REFERENCES compte (id) ON DELETE SET NULL
);

CREATE INDEX idx_acces_refuse_date ON acces_refuse (date_tentative DESC);
