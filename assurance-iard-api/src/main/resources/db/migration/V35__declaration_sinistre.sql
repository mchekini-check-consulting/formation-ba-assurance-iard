-- US-24 : déclarer un sinistre habitation ou auto. Complète T-05 (V26), sans modifier les migrations existantes.
-- Annulation : db/annulation/U35__declaration_sinistre.sql.
--
-- 1. Pièces jointes : 10 Mo au plus (RG7, décision BA du 26/11/2026 ; T-05 contrôlait 5 Mo), empreinte SHA-256 et
--    contenu conservé en base (jamais sur le disque, voir IA-241), comme les documents de T-03.
-- 2. Sinistre : corbeille (RG9), « à requalifier » (RG11), pièces manquantes (AC7), nombre de blessés (AC11, aucune
--    donnée médicale), date de l'arrêté de catastrophe naturelle (RG2), étape atteinte du brouillon (AC8).
--    « Tiers impliqué » et « blessés » n'ont plus de valeur par défaut : aucune réponse n'est présélectionnée
--    (RG commune) ; elles sont obligatoires à l'envoi.
-- 3. Référentiels : types de sinistres par produit (RG1, RG10 : ordre, actif, délai, garanties qui couvrent, gestes
--    d'urgence) et pièces attendues (RG1). Pas d'écran d'administration (US-39).

-- 1. Pièces jointes ------------------------------------------------------------------------------------------------
ALTER TABLE piece_jointe DROP CONSTRAINT ck_piece_jointe_taille;
ALTER TABLE piece_jointe ADD CONSTRAINT ck_piece_jointe_taille CHECK (taille_octets BETWEEN 1 AND 10485760);
ALTER TABLE piece_jointe ADD COLUMN empreinte VARCHAR(64);

CREATE TABLE piece_jointe_contenu (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piece_jointe_id   BIGINT                   NOT NULL,
    contenu           BYTEA                    NOT NULL,
    taille_octets     INTEGER                  NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_piece_jointe_contenu_piece UNIQUE (piece_jointe_id),
    CONSTRAINT fk_piece_jointe_contenu_piece FOREIGN KEY (piece_jointe_id) REFERENCES piece_jointe (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_piece_jointe_contenu_taille CHECK (taille_octets BETWEEN 1 AND 10485760),
    CONSTRAINT ck_piece_jointe_contenu_taille_reelle CHECK (taille_octets = OCTET_LENGTH(contenu))
);

-- 2. Sinistre -----------------------------------------------------------------------------------------------------
ALTER TABLE sinistre ADD COLUMN corbeille VARCHAR(12);
ALTER TABLE sinistre ADD COLUMN a_requalifier BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE sinistre ADD COLUMN pieces_manquantes BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE sinistre ADD COLUMN nombre_blesses SMALLINT;
ALTER TABLE sinistre ADD COLUMN date_arrete_catnat DATE;
ALTER TABLE sinistre ADD COLUMN etape SMALLINT NOT NULL DEFAULT 1;

UPDATE sinistre s SET corbeille = c.produit FROM contrat c WHERE c.id = s.contrat_id AND s.corbeille IS NULL;
UPDATE sinistre SET a_requalifier = TRUE WHERE type = 'AUTRE' AND statut = 'DECLARE';

-- Le brouillon est créé dès l'étape 1 (AC8), avant que la date ne soit connue (étape 2).
ALTER TABLE sinistre ALTER COLUMN date_survenance DROP NOT NULL;
ALTER TABLE sinistre ALTER COLUMN tiers_implique DROP DEFAULT;
ALTER TABLE sinistre ALTER COLUMN tiers_implique DROP NOT NULL;
ALTER TABLE sinistre ALTER COLUMN blesses DROP DEFAULT;
ALTER TABLE sinistre ALTER COLUMN blesses DROP NOT NULL;

ALTER TABLE sinistre ADD CONSTRAINT ck_sinistre_corbeille CHECK (corbeille IN ('AUTO', 'HABITATION'));
ALTER TABLE sinistre ADD CONSTRAINT ck_sinistre_etape CHECK (etape BETWEEN 1 AND 3);
ALTER TABLE sinistre ADD CONSTRAINT ck_sinistre_nombre_blesses CHECK (nombre_blesses IS NULL OR nombre_blesses >= 1);
-- Une déclaration envoyée a toutes ses réponses obligatoires : contrôlé par l'application à l'envoi, pas par une contrainte
-- (le script de données de test T-05, déjà sur main, crée un sinistre DECLARE sans ces champs ; le script US-24 le
-- complète ensuite).

CREATE INDEX idx_sinistre_brouillon_expire ON sinistre (brouillon_expire_le) WHERE statut = 'BROUILLON';

-- 3. Référentiels -------------------------------------------------------------------------------------------------
-- formules_couvrantes / options_couvrantes : codes de contrat.formule et contrat_option.code_option qui couvrent le
-- type (AC3, RG4). Vides pour « Autre » : jamais de message « non couvert » (RG11).
-- delai_jours_ouvres : RG2 (5 jours ouvrés, 2 pour un vol) ; delai_jours_arrete : 30 jours après l'arrêté (CatNat).
CREATE TABLE ref_type_sinistre (
    produit             VARCHAR(12)              NOT NULL,
    code                VARCHAR(20)              NOT NULL,
    libelle             VARCHAR(80)              NOT NULL,
    aide                VARCHAR(255),
    ordre               SMALLINT                 NOT NULL,
    actif               BOOLEAN                  NOT NULL DEFAULT TRUE,
    delai_jours_ouvres  SMALLINT,
    delai_jours_arrete  SMALLINT,
    formules_couvrantes TEXT[]                   NOT NULL DEFAULT '{}',
    options_couvrantes  TEXT[]                   NOT NULL DEFAULT '{}',
    gestes_urgence      TEXT[]                   NOT NULL DEFAULT '{}',
    date_creation       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_ref_type_sinistre PRIMARY KEY (produit, code),
    CONSTRAINT ck_ref_type_sinistre_produit CHECK (produit IN ('AUTO', 'HABITATION')),
    -- RG10 : « Autre / je ne sais pas » ne peut pas être désactivé.
    CONSTRAINT ck_ref_type_sinistre_autre_actif CHECK (code <> 'AUTRE' OR actif)
);

CREATE TABLE ref_piece_attendue (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit           VARCHAR(12)              NOT NULL,
    type_sinistre     VARCHAR(20)              NOT NULL,
    code              VARCHAR(30)              NOT NULL,
    libelle           VARCHAR(120)             NOT NULL,
    obligatoire       BOOLEAN                  NOT NULL,
    ordre             SMALLINT                 NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_ref_piece_attendue UNIQUE (produit, type_sinistre, code),
    CONSTRAINT fk_ref_piece_attendue_type FOREIGN KEY (produit, type_sinistre)
        REFERENCES ref_type_sinistre (produit, code)
);

