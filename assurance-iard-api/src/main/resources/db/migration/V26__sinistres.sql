-- T-05 : déclaration de sinistre et pièces jointes.
-- Aucune donnée médicale : seul le booléen « blessés » est conservé. Le numéro SIN-AAAA-NNNNNN est attribué à
-- l'envoi. La cohérence type de sinistre / produit du contrat est une règle de l'application (US-24).

CREATE TABLE sinistre (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero               VARCHAR(20),
    contrat_id           BIGINT                   NOT NULL,
    statut               VARCHAR(10)              NOT NULL DEFAULT 'BROUILLON',
    type                 VARCHAR(20)              NOT NULL,
    date_survenance      DATE                     NOT NULL,
    heure_survenance     TIME,
    lieu                 VARCHAR(255),
    description          TEXT,
    tiers_implique       BOOLEAN                  NOT NULL DEFAULT FALSE,
    tiers_infos          JSONB,
    blesses              BOOLEAN                  NOT NULL DEFAULT FALSE,
    declarant            VARCHAR(12),
    declarant_infos      JSONB,
    details              JSONB,
    hors_delai           BOOLEAN                  NOT NULL DEFAULT FALSE,
    explication_retard   TEXT,
    hors_periode_contrat BOOLEAN                  NOT NULL DEFAULT FALSE,
    declaration_honneur  BOOLEAN                  NOT NULL DEFAULT FALSE,
    declare_le           TIMESTAMP WITH TIME ZONE,
    brouillon_expire_le  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW() + INTERVAL '30 days',
    date_creation        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_sinistre_numero UNIQUE (numero),
    CONSTRAINT fk_sinistre_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT ck_sinistre_statut CHECK (statut IN ('BROUILLON', 'DECLARE')),
    CONSTRAINT ck_sinistre_type CHECK (type IN
        ('ACCIDENT_TIERS', 'ACCIDENT_SANS_TIERS', 'VOL', 'BRIS_GLACE', 'INCENDIE', 'CLIMATIQUE_CATNAT', 'AUTRE',
         'DEGAT_EAUX', 'VOL_CAMBRIOLAGE', 'RC_TIERS')),
    CONSTRAINT ck_sinistre_declarant CHECK (declarant IN ('SOUSCRIPTEUR', 'CONDUCTEUR', 'PROCHE')),
    -- Jamais dans le futur par rapport à la création (la date du jour est contrôlée par l'application).
    CONSTRAINT ck_sinistre_date_survenance CHECK (date_survenance <= CAST(date_creation AS DATE)),
    CONSTRAINT ck_sinistre_declare CHECK (statut <> 'DECLARE'
        OR (declaration_honneur AND numero IS NOT NULL AND declare_le IS NOT NULL))
);

CREATE INDEX idx_sinistre_contrat ON sinistre (contrat_id);

ALTER TABLE document
    ADD CONSTRAINT fk_document_sinistre FOREIGN KEY (sinistre_id) REFERENCES sinistre (id);

CREATE TABLE piece_jointe (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sinistre_id       BIGINT                   NOT NULL,
    type_piece        VARCHAR(30)              NOT NULL,
    nom_fichier       VARCHAR(255)             NOT NULL,
    format            VARCHAR(3)               NOT NULL,
    taille_octets     INTEGER                  NOT NULL,
    cle_stockage      VARCHAR(255),
    statut            VARCHAR(8)               NOT NULL DEFAULT 'STOCKEE',
    motif_refus       VARCHAR(255),
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_piece_jointe_sinistre FOREIGN KEY (sinistre_id) REFERENCES sinistre (id),
    CONSTRAINT ck_piece_jointe_format CHECK (format IN ('PDF', 'JPG', 'PNG')),
    -- Hypothèse non validée par la PO : 5 Mo maximum.
    CONSTRAINT ck_piece_jointe_taille CHECK (taille_octets BETWEEN 1 AND 5242880),
    CONSTRAINT ck_piece_jointe_statut CHECK (statut IN ('STOCKEE', 'REFUSEE'))
);

CREATE INDEX idx_piece_jointe_sinistre ON piece_jointe (sinistre_id);
