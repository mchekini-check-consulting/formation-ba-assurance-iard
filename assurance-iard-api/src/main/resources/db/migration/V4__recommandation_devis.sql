-- US-10 (RG4) : réponses aux questions de besoins et recommandation, pour alimenter la fiche conseil.
-- Aucune donnée personnelle : le prospect n'a pas encore de compte.
CREATE TABLE recommandation_devis (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         UUID NOT NULL,
    valeur_contenu    INTEGER NOT NULL,
    objets_valeur     BOOLEAN NOT NULL,
    appareils_couteux BOOLEAN NOT NULL,
    remboursement     VARCHAR(10) NOT NULL,
    assistance        BOOLEAN NOT NULL,
    litiges           BOOLEAN NOT NULL,
    priorite          VARCHAR(12) NOT NULL,
    formule           VARCHAR(12) NOT NULL,
    raisons           TEXT[] NOT NULL,
    options           TEXT[] NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_recommandation_devis_reference UNIQUE (reference)
);
