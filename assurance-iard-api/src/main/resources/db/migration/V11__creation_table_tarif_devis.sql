CREATE TABLE tarif_devis (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_devis UUID                     NOT NULL,
    id_tarif        UUID                     NOT NULL,
    code_postal     VARCHAR(5)               NOT NULL,
    type_logement   VARCHAR(50)              NOT NULL,
    surface         NUMERIC(10, 2)           NOT NULL,
    franchise       INTEGER,
    date_creation   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tarif_devis_reference UNIQUE (reference_devis)
);
