-- T-05 : documents versionnés, échéancier, factures et avenants.
-- Montants en décimal(10,2), en euros. Taxe = taxe sur les conventions d'assurance (pas de TVA).

CREATE TABLE document (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrat_id        BIGINT,
    devis_id          BIGINT,
    sinistre_id       BIGINT,
    type              VARCHAR(30)              NOT NULL,
    version           INTEGER                  NOT NULL DEFAULT 1,
    statut            VARCHAR(12)              NOT NULL DEFAULT 'EN_VIGUEUR',
    motif             VARCHAR(100),
    cle_stockage      VARCHAR(255),
    empreinte         VARCHAR(64),
    stocke            BOOLEAN                  NOT NULL DEFAULT FALSE,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_document_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT fk_document_devis FOREIGN KEY (devis_id) REFERENCES devis_enregistre (id),
    CONSTRAINT ck_document_type CHECK (type IN
        ('CONDITIONS_PARTICULIERES', 'CONDITIONS_GENERALES', 'IPID', 'FICHE_CONSEIL', 'MANDAT_SEPA', 'ECHEANCIER',
         'FACTURE', 'AVENANT', 'MEMO_VEHICULE', 'ATTESTATION', 'DEVIS', 'DECLARATION_SINISTRE')),
    CONSTRAINT ck_document_statut CHECK (statut IN ('EN_VIGUEUR', 'REMPLACE')),
    CONSTRAINT ck_document_version CHECK (version >= 1),
    CONSTRAINT ck_document_stocke CHECK (NOT stocke OR cle_stockage IS NOT NULL)
);

-- Une seule version EN_VIGUEUR par contrat et par type.
CREATE UNIQUE INDEX uk_document_en_vigueur ON document (contrat_id, type) WHERE statut = 'EN_VIGUEUR';
CREATE INDEX idx_document_contrat_type_statut ON document (contrat_id, type, statut);

CREATE TABLE echeance (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrat_id        BIGINT                   NOT NULL,
    date_echeance     DATE                     NOT NULL,
    montant_ht        NUMERIC(10, 2)           NOT NULL,
    taxe              NUMERIC(10, 2)           NOT NULL,
    montant_ttc       NUMERIC(10, 2)           NOT NULL,
    statut            VARCHAR(10)              NOT NULL DEFAULT 'A_VENIR',
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_echeance_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT ck_echeance_montant_ttc CHECK (montant_ttc = montant_ht + taxe),
    CONSTRAINT ck_echeance_statut CHECK (statut IN ('A_VENIR', 'PAYEE', 'IMPAYEE'))
);

CREATE INDEX idx_echeance_contrat ON echeance (contrat_id);

CREATE TABLE facture (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero            VARCHAR(20)              NOT NULL,
    contrat_id        BIGINT                   NOT NULL,
    periode_debut     DATE                     NOT NULL,
    periode_fin       DATE                     NOT NULL,
    montant_ht        NUMERIC(10, 2)           NOT NULL,
    taxe              NUMERIC(10, 2)           NOT NULL,
    montant_ttc       NUMERIC(10, 2)           NOT NULL,
    document_id       BIGINT,
    generee_le        TIMESTAMP WITH TIME ZONE NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_facture_numero UNIQUE (numero),
    CONSTRAINT fk_facture_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT fk_facture_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT ck_facture_montant_ttc CHECK (montant_ttc = montant_ht + taxe),
    CONSTRAINT ck_facture_periode CHECK (periode_fin >= periode_debut)
);

CREATE INDEX idx_facture_contrat ON facture (contrat_id);

CREATE TABLE avenant (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero            INTEGER                  NOT NULL,
    contrat_id        BIGINT                   NOT NULL,
    statut            VARCHAR(10)              NOT NULL DEFAULT 'EN_ATTENTE',
    date_effet        DATE                     NOT NULL,
    prime_avant_ttc   NUMERIC(10, 2)           NOT NULL,
    prime_apres_ttc   NUMERIC(10, 2)           NOT NULL,
    accepte_le        TIMESTAMP WITH TIME ZONE,
    accepte_ip        VARCHAR(45),
    document_id       BIGINT,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_avenant_numero UNIQUE (contrat_id, numero),
    CONSTRAINT fk_avenant_contrat FOREIGN KEY (contrat_id) REFERENCES contrat (id),
    CONSTRAINT fk_avenant_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT ck_avenant_numero CHECK (numero >= 1),
    CONSTRAINT ck_avenant_statut CHECK (statut IN ('EN_ATTENTE', 'ACCEPTE', 'ABANDONNE'))
);

-- Un seul avenant EN_ATTENTE par contrat.
CREATE UNIQUE INDEX uk_avenant_en_attente ON avenant (contrat_id) WHERE statut = 'EN_ATTENTE';

CREATE TABLE avenant_ligne (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avenant_id        BIGINT                   NOT NULL,
    code_option       VARCHAR(30)              NOT NULL,
    action            VARCHAR(10)              NOT NULL,
    prix_mensuel_ttc  NUMERIC(10, 2)           NOT NULL,
    date_creation     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_avenant_ligne_avenant FOREIGN KEY (avenant_id) REFERENCES avenant (id),
    CONSTRAINT ck_avenant_ligne_action CHECK (action IN ('AJOUT', 'RETRAIT'))
);

CREATE INDEX idx_avenant_ligne_avenant ON avenant_ligne (avenant_id);
