-- US-07 : lien de réinitialisation du mot de passe, valable 24 heures et utilisable une seule fois
CREATE TABLE lien_reinitialisation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id       BIGINT NOT NULL,
    jeton_hash      VARCHAR(64) NOT NULL,
    date_expiration TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_lien_reinitialisation_jeton UNIQUE (jeton_hash),
    CONSTRAINT fk_lien_reinitialisation_compte FOREIGN KEY (compte_id) REFERENCES compte (id) ON DELETE CASCADE
);

CREATE INDEX idx_lien_reinitialisation_compte ON lien_reinitialisation (compte_id);
