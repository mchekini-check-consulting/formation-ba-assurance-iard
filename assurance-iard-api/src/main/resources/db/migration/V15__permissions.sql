CREATE TABLE permission (
    id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    profil   VARCHAR(30) NOT NULL,
    rubrique VARCHAR(30) NOT NULL,
    droit    VARCHAR(30) NOT NULL,
    valeur   BOOLEAN NOT NULL,
    CONSTRAINT uk_permission UNIQUE (profil, rubrique, droit)
);

CREATE TABLE historique_permission (
    id                 BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    modifie_le         TIMESTAMP WITH TIME ZONE NOT NULL,
    modifie_par_email  VARCHAR(254) NOT NULL,
    profil             VARCHAR(30) NOT NULL,
    rubrique           VARCHAR(30) NOT NULL,
    droit              VARCHAR(30) NOT NULL,
    ancienne_valeur    BOOLEAN NOT NULL,
    nouvelle_valeur    BOOLEAN NOT NULL
);

