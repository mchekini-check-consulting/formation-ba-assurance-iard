-- US-31 étape 4 : souscripteur d'un devis auto, rattaché au compte lors de l'enregistrement.
CREATE TABLE souscripteur_auto (
    id               bigint generated by default as identity primary key,
    devis_auto_id    bigint not null unique references devis_auto(id),
    compte_id        bigint references compte(id),
    civilite         varchar(10)  not null,
    nom              varchar(100) not null,
    prenom           varchar(100) not null,
    date_naissance   date         not null,
    telephone        varchar(10)  not null,
    adresse          varchar(255) not null,
    code_postal      varchar(5)   not null,
    ville            varchar(100) not null,
    date_creation    timestamp with time zone not null,
    date_modification timestamp with time zone not null
);
