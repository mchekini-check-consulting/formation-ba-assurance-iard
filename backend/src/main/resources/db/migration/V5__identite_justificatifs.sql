-- US-13 : identité du client dans son compte, dossier de souscription et justificatifs déposés.
-- Les fichiers restent dans un dossier du serveur : la base ne garde que leur description.
ALTER TABLE compte
    ADD COLUMN civilite       VARCHAR(8),
    ADD COLUMN nom            VARCHAR(100),
    ADD COLUMN prenom         VARCHAR(100),
    ADD COLUMN date_naissance DATE,
    ADD COLUMN telephone      VARCHAR(10);

CREATE TABLE dossier_souscription (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id       BIGINT NOT NULL,
    reference_devis UUID NOT NULL,
    colocataires    TEXT[] NOT NULL,
    date_creation   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_dossier_souscription_devis UNIQUE (compte_id, reference_devis),
    CONSTRAINT fk_dossier_souscription_compte FOREIGN KEY (compte_id) REFERENCES compte (id) ON DELETE CASCADE,
    CONSTRAINT fk_dossier_souscription_devis FOREIGN KEY (reference_devis) REFERENCES recommandation_devis (reference)
);

CREATE TABLE justificatif (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id    BIGINT NOT NULL,
    categorie     VARCHAR(10) NOT NULL,
    type_document VARCHAR(20) NOT NULL,
    nom_fichier   VARCHAR(255) NOT NULL,
    type_fichier  VARCHAR(3) NOT NULL,
    taille        INTEGER NOT NULL,
    cle_stockage  VARCHAR(40) NOT NULL,
    CONSTRAINT uk_justificatif_categorie UNIQUE (dossier_id, categorie),
    CONSTRAINT fk_justificatif_dossier FOREIGN KEY (dossier_id) REFERENCES dossier_souscription (id) ON DELETE CASCADE
);
