-- US-12 : devis enregistré par un client. Les besoins restent dans recommandation_devis.
-- RGPD : date_dernier_contact sert à supprimer le devis 3 ans après le dernier contact du client.
CREATE TABLE devis_enregistre (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id            BIGINT NOT NULL REFERENCES compte (id),
    reference            UUID NOT NULL REFERENCES recommandation_devis (reference),
    statut               VARCHAR(30),
    residence            VARCHAR(12),
    type_logement        VARCHAR(12) NOT NULL,
    adresse              VARCHAR(255) NOT NULL,
    code_postal          VARCHAR(5) NOT NULL,
    ville                VARCHAR(100) NOT NULL,
    surface              INTEGER NOT NULL,
    nombre_pieces        VARCHAR(5),
    antecedent           VARCHAR(30),
    resilie_contrat      VARCHAR(30),
    assurance_antecedent VARCHAR(30),
    etage                VARCHAR(30),
    dependances          BOOLEAN,
    nombre_colocataires  VARCHAR(5),
    assureur_actuel      VARCHAR(100),
    nombre_sinistres     VARCHAR(5),
    formule              VARCHAR(12) NOT NULL,
    options              TEXT[] NOT NULL,
    franchise            VARCHAR(3) NOT NULL,
    prix_mensuel         NUMERIC(10, 2) NOT NULL,
    date_creation        TIMESTAMP WITH TIME ZONE NOT NULL,
    date_fin_validite    DATE NOT NULL,
    date_dernier_contact TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_devis_enregistre_compte_reference UNIQUE (compte_id, reference)
);
CREATE INDEX idx_devis_enregistre_reference ON devis_enregistre (reference);
CREATE INDEX idx_devis_enregistre_dernier_contact ON devis_enregistre (date_dernier_contact);
