-- US-14 : mandat de prélèvement SEPA d'un dossier de souscription.
-- L'IBAN n'est jamais conservé en entier : seuls ses 4 derniers caractères sont gardés.
-- Les champs vides correspondent à un mandat préparé (RUM attribuée) mais pas encore signé.
CREATE TABLE mandat_sepa (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id               BIGINT NOT NULL,
    rum                      VARCHAR(35) NOT NULL,
    titulaire                VARCHAR(140),
    iban_fin                 VARCHAR(4),
    jour_prelevement         INTEGER,
    date_debut               DATE,
    date_premier_prelevement DATE,
    date_creation            TIMESTAMP WITH TIME ZONE NOT NULL,
    date_signature           TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_mandat_sepa_dossier UNIQUE (dossier_id),
    CONSTRAINT uk_mandat_sepa_rum UNIQUE (rum),
    CONSTRAINT fk_mandat_sepa_dossier FOREIGN KEY (dossier_id) REFERENCES dossier_souscription (id) ON DELETE CASCADE
);
