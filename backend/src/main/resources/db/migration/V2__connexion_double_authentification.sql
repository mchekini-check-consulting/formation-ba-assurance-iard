-- US-06 : blocage après 5 échecs de mot de passe, code de vérification, session client
ALTER TABLE compte
    ADD COLUMN echecs_connexion INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN bloque_jusqu_a   TIMESTAMP WITH TIME ZONE;

CREATE TABLE code_verification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id       BIGINT NOT NULL,
    jeton_hash      VARCHAR(64) NOT NULL,
    code_hash       VARCHAR(100) NOT NULL,
    erreurs         INTEGER NOT NULL DEFAULT 0,
    date_expiration TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_code_verification_jeton UNIQUE (jeton_hash),
    CONSTRAINT fk_code_verification_compte FOREIGN KEY (compte_id) REFERENCES compte (id) ON DELETE CASCADE
);

CREATE INDEX idx_code_verification_compte ON code_verification (compte_id);

CREATE TABLE session_client (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compte_id       BIGINT NOT NULL,
    jeton_hash      VARCHAR(64) NOT NULL,
    date_expiration TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_session_client_jeton UNIQUE (jeton_hash),
    CONSTRAINT fk_session_client_compte FOREIGN KEY (compte_id) REFERENCES compte (id) ON DELETE CASCADE
);

CREATE INDEX idx_session_client_compte ON session_client (compte_id);
