create table calcul_tarif (
    id             bigint generated by default as identity primary key,
    id_tarif       uuid                     not null unique,
    version_grille varchar(50)              not null,
    tarifable      boolean                  not null,
    donnees_recues jsonb                    not null,
    resultat       jsonb                    not null,
    date_calcul    timestamp with time zone not null,
    date_validite  date
);
