create table grille_tarifaire (
    id         bigint generated by default as identity primary key,
    version    varchar(50) not null unique,
    date_debut date        not null,
    date_fin   date,
    constraint grille_tarifaire_dates check (date_fin is null or date_fin >= date_debut)
);

create table parametre_tarifaire (
    id        bigint generated by default as identity primary key,
    grille_id bigint       not null references grille_tarifaire (id),
    categorie varchar(50)  not null,
    cle       varchar(50)  not null,
    valeur    varchar(255) not null,
    constraint parametre_tarifaire_unique unique (grille_id, categorie, cle)
);
