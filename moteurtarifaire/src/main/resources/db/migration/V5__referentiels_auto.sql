-- T-05 : référentiels de tarification auto (structure seule ; les données sont chargées par T-04).
-- Réutilise le versionnement existant : chaque ligne appartient à une version de grille_tarifaire (grille_id).
-- parametre_tarifaire (clé / valeur, habitation) n'est pas modifiée.

create table ref_formule (
    id                bigint generated by default as identity primary key,
    grille_id         bigint                   not null references grille_tarifaire (id),
    code              varchar(10)              not null,
    libelle           varchar(60)              not null,
    franchise         numeric(10, 2),
    prix_mensuel_base numeric(10, 2)           not null,
    ordre             integer                  not null,
    date_creation     timestamp with time zone not null default now(),
    date_modification timestamp with time zone not null default now(),
    constraint ref_formule_unique unique (grille_id, code),
    constraint ref_formule_code check (code in ('TIERS', 'INTER', 'TR'))
);

create table ref_option (
    id                   bigint generated by default as identity primary key,
    grille_id            bigint                   not null references grille_tarifaire (id),
    code                 varchar(30)              not null,
    libelle              varchar(100)             not null,
    prix_mensuel         numeric(10, 2)           not null,
    produit              varchar(12)              not null,
    obligatoire          boolean                  not null default false,
    formules_compatibles text[]                   not null default '{}',
    date_creation        timestamp with time zone not null default now(),
    date_modification    timestamp with time zone not null default now(),
    constraint ref_option_unique unique (grille_id, code),
    constraint ref_option_produit check (produit in ('HABITATION', 'AUTO'))
);

-- Coefficients simples : par tranche (âge, bonus-malus, valeur du véhicule) ou par valeur (usage).
create table ref_tarif (
    id                bigint generated by default as identity primary key,
    grille_id         bigint                   not null references grille_tarifaire (id),
    critere           varchar(20)              not null,
    borne_min         numeric(10, 2),
    borne_max         numeric(10, 2),
    valeur            varchar(30),
    coefficient       numeric(6, 3)            not null,
    date_creation     timestamp with time zone not null default now(),
    date_modification timestamp with time zone not null default now(),
    constraint ref_tarif_critere check (critere in ('AGE', 'BONUS_MALUS', 'USAGE', 'VALEUR_VEHICULE')),
    constraint ref_tarif_bornes check (borne_min is null or borne_max is null or borne_max >= borne_min),
    constraint ref_tarif_coefficient check (coefficient > 0)
);

create index ref_tarif_grille_critere on ref_tarif (grille_id, critere);
